import Foundation

/// The broad category of a clipboard entry, used for display and filtering.
enum ClipKind: String, Codable, CaseIterable {
    case text
    case richText
    case image
    case file
    case other

    var symbolName: String {
        switch self {
        case .text: return "text.alignleft"
        case .richText: return "doc.richtext"
        case .image: return "photo"
        case .file: return "doc"
        case .other: return "questionmark.square.dashed"
        }
    }
}

/// Lightweight metadata for one history entry. The actual pasteboard data lives
/// in a separate blob on disk (see `ClipPayload`) so the index stays small.
struct ClipItem: Codable, Identifiable, Hashable {
    let id: UUID
    /// When this content was most recently copied (re-copying bumps it to the top).
    var date: Date
    let kind: ClipKind
    /// Short, single-string description used for list rows and search.
    let preview: String
    /// Total bytes on disk attributable to this item (payload + thumbnail).
    let byteSize: Int
    /// SHA-256 of the pasteboard contents, used to de-duplicate.
    let contentHash: String
    let sourceAppName: String?
    let sourceBundleID: String?
    let imagePixelWidth: Int?
    let imagePixelHeight: Int?
    let hasThumbnail: Bool
}

/// Every representation of every pasteboard item, keyed by UTI string, exactly
/// as captured. Restoring writes all of them back so the target app can pick
/// its preferred flavor (RTF vs plain text, PNG vs TIFF, etc).
struct ClipPayload: Codable {
    var items: [[String: Data]]

    var plainText: String? {
        for item in items {
            if let data = item[UTType.plainText], let s = String(data: data, encoding: .utf8) {
                return s
            }
        }
        return nil
    }

    var fileURLs: [URL] {
        items.compactMap { item in
            item[UTType.fileURL].flatMap { URL(dataRepresentation: $0, relativeTo: nil) }
        }
    }

    var imageData: Data? {
        for item in items {
            for type in UTType.imageTypes {
                if let data = item[type] { return data }
            }
        }
        return nil
    }
}

/// Raw UTI strings we care about. (Kept as strings since that's what the
/// pasteboard and our payload dictionaries use.)
enum UTType {
    static let plainText = "public.utf8-plain-text"
    static let rtf = "public.rtf"
    static let rtfd = "com.apple.flat-rtfd"
    static let html = "public.html"
    static let fileURL = "public.file-url"
    static let png = "public.png"
    static let tiff = "public.tiff"
    static let jpeg = "public.jpeg"
    static let heic = "public.heic"
    static let pdf = "com.adobe.pdf"

    static let imageTypes = [png, tiff, jpeg, heic]
    static let richTextTypes = [rtf, rtfd, html]

    /// Markers set by password managers and other apps (see nspasteboard.org)
    /// asking clipboard managers not to record this content.
    static let ignoredMarkers: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "com.typeit4me.clipping",
        "de.petermaurer.TransientPasteboardType",
        "Pasteboard generator type",
        "net.antelle.keeweb",
    ]
}
